def agent_manager_text(
    *, nickname: str, username: str | None, telegram_id: int, phone: str
) -> str:
    """Уведомление админам о новом агенте."""
    who = html.escape(nickname) or "—"
    if username:
        who += f" (@{html.escape(username)})"
    return (
        "🤝 <b>Новый агент</b>\n"
        "\n"
        f"👤 {who}\n"
        f"🔗 <a href='tg://user?id={telegram_id}'>Написать</a>\n"
        f"📱 Телефон: {html.escape(phone)}"
    )
